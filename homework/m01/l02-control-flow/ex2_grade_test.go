package l02controlflow

import "testing"

func TestGrade(t *testing.T) {
	tests := []struct {
		name  string
		score int
		want  string
	}{
		{"максимум", 100, "отлично"},
		{"нижняя граница отлично", 90, "отлично"},
		{"верхняя граница хорошо", 89, "хорошо"},
		{"нижняя граница хорошо", 75, "хорошо"},
		{"верхняя граница удовлетворительно", 74, "удовлетворительно"},
		{"нижняя граница удовлетворительно", 60, "удовлетворительно"},
		{"верхняя граница неуда", 59, "неудовлетворительно"},
		{"ноль", 0, "неудовлетворительно"},
		{"отрицательные", -1, "ошибка"},
		{"больше ста", 101, "ошибка"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := Grade(tt.score); got != tt.want {
				t.Errorf("Grade(%d) = %q, want %q", tt.score, got, tt.want)
			}
		})
	}
}
