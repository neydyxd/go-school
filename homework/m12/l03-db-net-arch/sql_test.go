package l03dbnetarch

import "testing"

func TestQueries(t *testing.T) {
	runCases(t, []sqlCase{
		{
			file: "q01_second_salary.sql",
			want: [][]string{{"300000.00"}},
			hint: "при ORDER BY salary DESC значения NULL идут первыми, а одинаковые максимумы надо схлопнуть; надёжно: max(salary) среди тех, кто меньше максимума",
		},
		{
			file:   "q01_second_salary.sql",
			before: `DELETE FROM logins; DELETE FROM employees WHERE id <> 1`,
			want:   [][]string{{"NULL"}},
			hint:   "в компании один сотрудник: ответ одна строка с NULL, а LIMIT/OFFSET возвращает ноль строк (агрегат без строк всё равно даёт одну строку)",
		},
		{
			file: "q02_above_manager.sql",
			want: [][]string{{"Дина", "320000.00", "Борис"}, {"Жанна", "210000.00", "Егор"}},
			hint: "нужно соединение таблицы с самой собой: employees e JOIN employees m ON m.id = e.manager_id; «больше» значит строго больше (Лев получает столько же, сколько Кира)",
		},
		{
			file:    "q03_top3_per_department.sql",
			ordered: true,
			want: [][]string{
				{"Разработка", "Дина", "320000.00"},
				{"Разработка", "Анна", "300000.00"},
				{"Разработка", "Борис", "250000.00"},
				{"Разработка", "Вера", "250000.00"},
				{"Продажи", "Жанна", "210000.00"},
				{"Продажи", "Егор", "200000.00"},
				{"Продажи", "Зоя", "150000.00"},
				{"Поддержка", "Кира", "120000.00"},
				{"Поддержка", "Лев", "120000.00"},
			},
			hint: "три различных значения с равенствами это dense_rank() OVER (PARTITION BY отдел ORDER BY salary DESC) <= 3; row_number отрежет Веру, rank пропустит место; NULL при DESC идёт первым, исключи зарплаты NULL",
		},
		{
			file:    "q03_top3_per_department.sql",
			ordered: true,
			// в «Поддержке» станет 130, 130, 120, 120, 110: три различных значения, все пятеро в ответе
			before: `INSERT INTO employees (id, name, salary, department_id) VALUES
				(20, 'Ника', 130000, 3), (21, 'Олег', 130000, 3), (22, 'Пётр', 110000, 3)`,
			want: [][]string{
				{"Разработка", "Дина", "320000.00"},
				{"Разработка", "Анна", "300000.00"},
				{"Разработка", "Борис", "250000.00"},
				{"Разработка", "Вера", "250000.00"},
				{"Продажи", "Жанна", "210000.00"},
				{"Продажи", "Егор", "200000.00"},
				{"Продажи", "Зоя", "150000.00"},
				{"Поддержка", "Ника", "130000.00"},
				{"Поддержка", "Олег", "130000.00"},
				{"Поддержка", "Кира", "120000.00"},
				{"Поддержка", "Лев", "120000.00"},
				{"Поддержка", "Пётр", "110000.00"},
			},
			hint: "нужны три различных ЗНАЧЕНИЯ зарплаты: при 130, 130, 120, 120, 110 в ответе все пятеро; rank() даст Петру место 5, а порог «третья строка по убыванию» равен 120; бери dense_rank()",
		},
		{
			file: "q04_duplicate_emails.sql",
			want: [][]string{{"zoya@corp.ru", "2"}, {"team@corp.ru", "2"}},
			hint: "группируй по lower(email) и оставь HAVING count(*) > 1; NULL при GROUP BY собираются в одну группу, их надо отфильтровать",
		},
		{
			file: "q05_empty_departments.sql",
			want: [][]string{{"Маркетинг"}, {"HR"}},
			hint: "NOT IN (SELECT department_id FROM employees) ничего не вернёт: у Майи department_id NULL; используй NOT EXISTS или LEFT JOIN ... WHERE e.id IS NULL",
		},
		{
			file:    "q06_running_total.sql",
			ordered: true,
			want: [][]string{
				{"2024-03-01T00:00:00Z", "1500.00", "1500.00"},
				{"2024-03-02T00:00:00Z", "200.00", "1700.00"},
				{"2024-03-04T00:00:00Z", "600.00", "2300.00"},
				{"2024-03-05T00:00:00Z", "50.00", "2350.00"},
			},
			hint: "сначала GROUP BY day, потом оконная сумма по дневным суммам: sum(sum(amount)) OVER (ORDER BY day); окно по сырым строкам даёт несколько строк на день",
		},
		{
			file:    "q07_login_streak.sql",
			ordered: true,
			want:    [][]string{{"Дина", "4"}, {"Анна", "3"}, {"Борис", "1"}, {"Жанна", "1"}},
			hint:    "приём «острова»: у дней одной серии day - row_number() одинаковое; сначала убери дубли дней (DISTINCT), иначе нумерация съедет; вычитай из date число, а не день месяца, чтобы серия шла через 29 февраля",
		},
	})
}
