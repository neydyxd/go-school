// множитель 10, а не 5, как в соседних: решения на container/heap делают
// миллионы вызовов через интерфейс, и -race замедляет их сильнее обычного.
// Неверная асимптотика под -race замедляется так же и всё равно не уложится.
const raceScale = 10
