package l03sqladvanced

import "testing"

func TestQueries(t *testing.T) {
	runCases(t, []sqlCase{
		{
			file: "q01_books_authors.sql",
			want: [][]string{
				{"Война и мир", "Лев Толстой"},
				{"Анна Каренина", "Лев Толстой"},
				{"Преступление и наказание", "Фёдор Достоевский"},
				{"Идиот", "Фёдор Достоевский"},
				{"Мастер и Маргарита", "Михаил Булгаков"},
				{"Собачье сердце", "Михаил Булгаков"},
				{"Белая гвардия", "Михаил Булгаков"},
				{"1984", "Джордж Оруэлл"},
				{"Скотный двор", "Джордж Оруэлл"},
				{"451 градус по Фаренгейту", "Рэй Брэдбери"},
				{"Марсианские хроники", "Рэй Брэдбери"},
				{"Убийство в «Восточном экспрессе»", "Агата Кристи"},
				{"И никого не стало", "Агата Кристи"},
				{"Пикник на обочине", "Братья Стругацкие"},
				{"Трудно быть богом", "Братья Стругацкие"},
				{"Язык программирования Go", "Алан Донован"},
				{"Русские народные сказки", "NULL"},
			},
			hint: "INNER JOIN выбрасывает книгу без автора; нужен books LEFT JOIN authors",
		},
		{
			file: "q02_orders_per_customer.sql",
			// тёзка: второй Глеб Орлов без заказов
			before: `INSERT INTO customers (name, email, city, registered_at) VALUES ('Глеб Орлов', 'gleb2@example.com', 'Казань', '2024-08-01')`,
			want: [][]string{
				{"Анна Смирнова", "3"}, {"Борис Петров", "2"}, {"Вера Козлова", "1"},
				{"Глеб Орлов", "2"}, {"Глеб Орлов", "0"}, {"Дина Сафина", "1"}, {"Егор Белов", "0"},
				{"Жанна Ким", "1"}, {"Зоя Морозова", "0"}, {"Игорь Лебедев", "1"},
				{"Кира Власова", "1"},
			},
			hint: "INNER JOIN теряет клиентов без заказов, а count(*) после LEFT JOIN даёт им 1 (строка с NULL тоже строка); считай count(o.id). Группируй по c.id: тёзки это разные клиенты",
		},
		{
			file: "q03_authors_without_books.sql",
			want: [][]string{{"Харуки Мураками"}, {"Козьма Прутков"}},
			hint: "id NOT IN (SELECT author_id FROM books) возвращает пустоту, потому что среди author_id есть NULL; используй NOT EXISTS или LEFT JOIN ... WHERE b.id IS NULL",
		},
		{
			file: "q04_books_per_category.sql",
			// вторая «Классика» (классика программирования) в разделе Нон-фикшн, пустая
			before: `INSERT INTO categories (id, name, parent_id) VALUES (9, 'Классика', 6)`,
			want: [][]string{
				{"Художественная литература", "1"}, {"Классика", "5"}, {"Классика", "0"},
				{"Фантастика", "4"}, {"Антиутопия", "3"}, {"Детектив", "2"}, {"Нон-фикшн", "0"},
				{"Программирование", "1"}, {"Поэзия", "0"},
			},
			hint: "пустые категории теряются при INNER JOIN и получают 1 при count(*); нужен categories LEFT JOIN books и count(b.id), группировка по c.id (названия могут совпадать)",
		},
		{
			file:    "q05_revenue_by_category.sql",
			ordered: true,
			// граница: выручка «Детектива» ровно 2000, «больше 2000» её не включает
			before: `INSERT INTO orders (id, customer_id, status, created_at) VALUES (13, 6, 'paid', '2024-07-30 12:00:00+00');
				INSERT INTO order_items (order_id, book_id, qty, price) VALUES (13, 12, 2, 595.00)`,
			want: [][]string{
				{"Антиутопия", "3810.00"},
				{"Классика", "3666.00"},
				{"Фантастика", "2111.00"},
			},
			hint: "условие на сумму группы пишется в HAVING sum(...) > 2000; WHERE фильтрует отдельные позиции до группировки. Не забудь status IN ('paid', 'shipped')",
		},
		{
			file:    "q06_popular_books.sql",
			ordered: true,
			want:    [][]string{{"1984", "2"}, {"Мастер и Маргарита", "2"}},
			hint:    "покупатель считается один раз: count(DISTINCT o.customer_id); при равенстве buyers сортируй по title",
		},
		{
			file:    "q07_above_average.sql",
			ordered: true,
			want: [][]string{
				{"Язык программирования Go", "2100.00"},
				{"Война и мир", "1200.00"},
				{"Анна Каренина", "850.00"},
				{"Мастер и Маргарита", "720.00"},
			},
			hint: "WHERE price > (SELECT avg(price) FROM books); avg сам пропускает NULL, а COALESCE(price, 0) занизит среднее",
		},
		{
			file: "q08_top_in_category.sql",
			// книга без цены в категории: при DESC NULL идёт первым
			before: `INSERT INTO books (id, title, author_id, category_id, price, year, pages) VALUES (18, 'Черновик', 6, 5, NULL, NULL, 100)`,
			want: [][]string{
				{"Художественная литература", "Русские народные сказки", "300.00"},
				{"Классика", "Война и мир", "1200.00"},
				{"Фантастика", "Марсианские хроники", "510.00"},
				{"Антиутопия", "1984", "540.00"},
				{"Детектив", "И никого не стало", "450.00"},
				{"Детектив", "Убийство в «Восточном экспрессе»", "450.00"},
				{"Программирование", "Язык программирования Go", "2100.00"},
			},
			hint: "row_number() оставит одну книгу из двух равных по цене детективов; при ничьих нужен rank() или dense_rank() = 1 (PARTITION BY категории). Книги без цены исключи: при DESC NULL окажется первым",
		},
		{
			file:    "q09_running_total.sql",
			ordered: true,
			// заказ с большим id, но более ранней датой: порядок по created_at, а не по id
			before: `INSERT INTO orders (id, customer_id, status, created_at) VALUES (13, 1, 'paid', '2024-03-01 12:00:00+00');
				INSERT INTO order_items (order_id, book_id, qty, price) VALUES (13, 16, 1, 300.00)`,
			want: [][]string{
				{"1", "13", "300.00", "300.00"},
				{"1", "1", "2280.00", "2580.00"},
				{"1", "3", "970.00", "3550.00"},
				{"1", "8", "585.00", "4135.00"},
				{"2", "2", "2241.00", "2241.00"},
				{"2", "11", "1330.00", "3571.00"},
				{"3", "4", "648.00", "648.00"},
				{"4", "12", "1233.00", "1233.00"},
				{"5", "6", "810.00", "810.00"},
				{"7", "7", "2190.00", "2190.00"},
			},
			hint: "сначала посчитай сумму каждого заказа (GROUP BY o.id), потом sum(total) OVER (PARTITION BY customer_id ORDER BY created_at); порядок по времени, а не по id",
		},
		{
			file:    "q10_monthly_revenue.sql",
			ordered: true,
			want: [][]string{
				{"2024-03", "4521.00", "NULL"},
				{"2024-04", "1618.00", "4521.00"},
				{"2024-05", "3000.00", "1618.00"},
				{"2024-06", "585.00", "3000.00"},
				{"2024-07", "2563.00", "585.00"},
			},
			hint: "сгруппируй по месяцу в CTE, затем lag(revenue) OVER (ORDER BY month); учитывай только 'paid' и 'shipped'",
		},
		{
			file:    "q11_category_tree.sql",
			ordered: true,
			// четвёртый уровень: ручной UNION на три уровня не сработает
			before: `INSERT INTO categories (id, name, parent_id) VALUES (9, 'Киберпанк', 4)`,
			want: [][]string{
				{"Художественная литература", "1"},
				{"Детектив", "2"},
				{"Классика", "2"},
				{"Поэзия", "2"},
				{"Фантастика", "2"},
				{"Антиутопия", "3"},
				{"Киберпанк", "4"},
			},
			hint: "якорь WITH RECURSIVE выбирает корень с level 1, рекурсивная часть присоединяет categories c ON c.parent_id = tree.id с level + 1",
		},
		{
			file:    "q12_big_spenders.sql",
			ordered: true,
			want: [][]string{
				{"Анна Смирнова", "3835.00"},
				{"Борис Петров", "3571.00"},
				{"Жанна Ким", "2190.00"},
			},
			hint: "среднее берётся по тратам клиентов из CTE (avg(total) FROM spent), а не по всем клиентам и не по отдельным позициям",
		},
	})
}
