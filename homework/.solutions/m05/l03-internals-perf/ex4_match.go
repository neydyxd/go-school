package l03internalsperf

import "math/bits"

// Контрольное слово группы swiss-таблицы: 8 байт, по байту на слот. Байт 0
// (младший) описывает слот 0, байт 7 (старший) слот 7. Кодировка из
// internal/runtime/maps/group.go:
//
//	1000 0000  (0x80) пустой слот
//	1111 1110  (0xFE) удалённый слот (надгробие)
//	0hhh hhhh         занятый слот, младшие 7 бит это H2 хеша ключа
//
// Результат сопоставления это тоже uint64: в байте i стоит 0x80, если слот
// i подошёл, иначе 0x00. Например, совпадение в слотах 0 и 2 даёт
// 0x0000000000800080.
const (
	CtrlEmpty   = 0x80
	CtrlDeleted = 0xFE
)

const (
	lsb = 0x0101010101010101
	msb = 0x8080808080808080
	l7b = 0x7f7f7f7f7f7f7f7f
)

// MatchH2: после XOR совпавшие байты нулевые. Байт x нулевой, если
// ни его старший бит, ни (младшие 7 бит + 0x7F) не дают единицы в бите 7.
// Сумма младших 7 бит с 0x7F не больше 0xFE, перенос в соседний байт
// невозможен, поэтому ложных срабатываний нет.
func MatchH2(ctrl uint64, h2 uint8) uint64 {
	x := ctrl ^ (lsb * uint64(h2))
	return ^((x&l7b + l7b) | x) & msb
}

// MatchEmpty: пустой байт это ровно 0x80. Байт 0x80 это единственный
// байт со старшим битом и нулевыми младшими семью: проверяем оба условия.
func MatchEmpty(ctrl uint64) uint64 {
	return ctrl & ^(ctrl&l7b + l7b) & msb
}

// FirstSlot: номер младшего установленного бита, делённый на 8.
func FirstSlot(match uint64) int {
	if match == 0 {
		return -1
	}
	return bits.TrailingZeros64(match) / 8
}
