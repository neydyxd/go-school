package l08sorting

// SortColors сортирует на месте слайс, где встречаются только 0, 1 и 2
// (например, приоритеты задач: низкий, средний, высокий), за O(n) и O(1)
// дополнительной памяти. Пакеты sort и slices не используй.
// На собесе ждут один проход трёхчастным разбиением (то же, что в быстрой
// сортировке с опорным 1); подсчёт в два прохода тоже верен, но это
// запасной ответ, тест их не различает.
//
// Ожидаемая сложность: O(n). Пузырёк или вставки не уложатся.
func SortColors(nums []int) {
	lo, i, hi := 0, 0, len(nums) // [0, lo) нули, [lo, i) единицы, [hi, n) двойки
	for i < hi {
		switch nums[i] {
		case 0:
			nums[lo], nums[i] = nums[i], nums[lo]
			lo++
			i++
		case 2:
			hi--
			nums[hi], nums[i] = nums[i], nums[hi] // пришедший с конца ещё не проверен, i не двигаем
		default:
			i++
		}
	}
}
