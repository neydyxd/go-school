package l03hashing

// IsAnagram сообщает, является ли b анаграммой a: состоит из тех же
// символов (рун) в тех же количествах, возможно в другом порядке.
// Регистр различается, пробелы считаются обычными символами.
// Две пустые строки анаграммы друг друга.
//
// Сравнивай руны, а не байты: у разных строк может совпадать набор байтов.
// Ожидаемая сложность: O(n) по времени.
func IsAnagram(a, b string) bool {
	cnt := make(map[rune]int)
	for _, r := range a {
		cnt[r]++
	}
	for _, r := range b {
		cnt[r]--
	}
	// Проверяем все счётчики, а не только длину в байтах: у невалидного
	// UTF-8 каждый битый байт range превращает в U+FFFD, и равная длина
	// в байтах уже не означает равное число рун.
	for _, c := range cnt {
		if c != 0 {
			return false
		}
	}
	return true
}
