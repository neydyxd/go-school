package l01bigo

// SingleNumber получает непустой слайс, в котором каждое число встречается
// ровно два раза, кроме одного, которое встречается один раз. Верни его.
// Числа могут быть отрицательными.
//
// Ожидаемая сложность: O(n) по времени и O(1) по дополнительной памяти
// (подсказка: подумай про XOR, оператор ^ в Go).
func SingleNumber(nums []int) int {
	x := 0
	for _, v := range nums {
		x ^= v // a^a = 0, a^0 = a, порядок не важен
	}
	return x
}
