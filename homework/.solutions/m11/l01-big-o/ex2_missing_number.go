// MissingNumber получает n разных чисел из диапазона [0, n], то есть
// ровно одного числа из диапазона не хватает. Верни это число.
// Для пустого слайса ответ 0 (диапазон [0, 0], и 0 отсутствует).
//
// Ожидаемая сложность: O(n) по времени и O(1) по дополнительной памяти.
func MissingNumber(nums []int) int {
	// XOR всех индексов 0..n и всех значений: пары взаимно уничтожаются,
	// остаётся пропущенное число. В отличие от формулы суммы, не может
	// переполниться ни при каком n.
	x := len(nums)
	for i, v := range nums {
		x ^= i ^ v
	}
	return x
}
