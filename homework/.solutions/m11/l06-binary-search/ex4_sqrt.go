package l06binarysearch

// Sqrt возвращает целую часть квадратного корня из x >= 0, то есть
// наибольшее r, для которого r*r <= x. Sqrt(8) = 2, Sqrt(9) = 3.
// x может быть любым неотрицательным int, вплоть до math.MaxInt64.
// Напиши бинарный поиск руками, без пакетов sort и slices.
//
// Подвохи: mid*mid переполняет int на больших x, а math.Sqrt работает
// с float64 и ошибается на больших x, у которых не хватает точности.
// Перебор r = 0, 1, 2... слишком медленный.
func Sqrt(x int) int {
	// ищем последнее r с r*r <= x; сравниваем r <= x/r, чтобы не переполниться
	lo, hi := 0, min(x, 3037000499) // 3037000499 это floor(sqrt(MaxInt64))
	for lo < hi {
		mid := lo + (hi-lo+1)/2 // округляем вверх, иначе lo = mid зациклится
		if mid <= x/mid {
			lo = mid
		} else {
			hi = mid - 1
		}
	}
	return lo
}
