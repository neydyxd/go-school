package l12dpgreedy

// ClimbStairs возвращает число способов подняться на лестницу из n
// ступенек, если за шаг можно подняться на 1 или на 2 ступеньки.
// Порядок шагов важен: 1+2 и 2+1 это разные способы. 1 <= n <= 90
// (ответ для 90 ещё помещается в int).
//
// Ожидаемая сложность: O(n) по времени, O(1) памяти. Рекурсия
// f(n) = f(n-1) + f(n-2) без запоминания делает экспоненциальное число
// вызовов и на n = 90 не закончится никогда.
func ClimbStairs(n int) int {
	// f(i) = f(i-1) + f(i-2): на ступеньку i приходим с i-1 или с i-2.
	// Храним только два последних значения.
	prev, cur := 1, 1 // f(0), f(1)
	for i := 2; i <= n; i++ {
		prev, cur = cur, prev+cur
	}
	return cur
}
