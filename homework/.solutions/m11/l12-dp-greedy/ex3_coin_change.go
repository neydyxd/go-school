package l12dpgreedy

// CoinChange возвращает наименьшее число монет, которыми можно набрать
// сумму amount. Номиналы coins положительные и различные, монет каждого
// номинала сколько угодно. Если набрать нельзя, верни -1. Для amount == 0
// ответ 0.
//
// Жадный алгоритм «бери самую крупную монету» здесь неверен: для монет
// {1, 3, 4} и суммы 6 он даст 4+1+1, а оптимум 3+3.
//
// Ожидаемая сложность: O(amount * len(coins)). Рекурсия без запоминания
// экспоненциальна и не уложится в лимит.
func CoinChange(coins []int, amount int) int {
	// dp[s] это минимум монет для суммы s; amount+1 играет роль
	// «бесконечности»: больше amount монет не понадобится никогда
	dp := make([]int, amount+1)
	for s := 1; s <= amount; s++ {
		dp[s] = amount + 1
		for _, c := range coins {
			if c <= s && dp[s-c]+1 < dp[s] {
				dp[s] = dp[s-c] + 1
			}
		}
	}
	if dp[amount] > amount {
		return -1
	}
	return dp[amount]
}
