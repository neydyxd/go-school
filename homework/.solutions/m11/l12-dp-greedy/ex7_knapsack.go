package l12dpgreedy

// Knapsack решает задачу о рюкзаке 0/1: есть предметы с весами
// weights[i] >= 1 и ценностями values[i] >= 0, каждый можно взять не
// больше одного раза. Верни наибольшую суммарную ценность предметов
// с суммарным весом не больше capacity >= 0.
//
// Ожидаемая сложность: O(n * capacity) по времени, O(capacity) памяти
// при одномерной таблице. Перебор 2^n подмножеств не уложится в лимит.
// Осторожно с направлением цикла по весу в одномерной таблице: в одну
// сторону получится рюкзак 0/1, в другую рюкзак, где каждый предмет
// можно брать сколько угодно раз.
func Knapsack(weights, values []int, capacity int) int {
	// dp[c] это лучшая ценность при вместимости c среди уже
	// рассмотренных предметов
	dp := make([]int, capacity+1)
	for i, w := range weights {
		// вес идёт сверху вниз: dp[c-w] ещё не учитывает предмет i,
		// поэтому он попадёт в рюкзак не больше одного раза
		for c := capacity; c >= w; c-- {
			dp[c] = max(dp[c], dp[c-w]+values[i])
		}
	}
	return dp[capacity]
}
