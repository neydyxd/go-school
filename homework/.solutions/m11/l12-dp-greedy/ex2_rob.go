package l12dpgreedy

// Rob: вдоль улицы стоят дома, в доме i лежит nums[i] >= 0 денег.
// Нельзя грабить два соседних дома. Верни наибольшую сумму, которую
// можно унести. Для пустой улицы ответ 0.
//
// Ожидаемая сложность: O(n) по времени, O(1) памяти. Перебор всех
// подмножеств домов (или рекурсия без запоминания) экспоненциален.
func Rob(nums []int) int {
	// take: лучшая сумма, если последний рассмотренный дом ограблен,
	// skip: если пропущен
	take, skip := 0, 0
	for _, v := range nums {
		take, skip = skip+v, max(take, skip)
	}
	return max(take, skip)
}
