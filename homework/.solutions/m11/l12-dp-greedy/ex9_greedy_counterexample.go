package l12dpgreedy

// GreedyCounterexample проверяет, работает ли жадный размен для набора
// монет coins: «пока сумма не ноль, бери самую крупную монету, которая
// влезает». Верни наименьшую сумму, на которой жадный алгоритм тратит
// больше монет, чем оптимальный, или -1, если такой суммы нет.
//
// Гарантируется: номиналы различны, отсортированы по возрастанию,
// coins[0] == 1 (значит, любую сумму можно набрать), len(coins) >= 1,
// все номиналы не больше 10^5.
// Достаточно проверить суммы меньше coins[n-2] + coins[n-1]: если
// контрпример существует, наименьший из них лежит ниже этой границы
// (теорема Козена и Закса, 1994). Для одной монеты контрпримера нет.
//
// Ожидаемая сложность: O(limit * n), где limit = coins[n-2] + coins[n-1]:
// одна таблица оптимумов на все суммы до границы.
func GreedyCounterexample(coins []int) int {
	n := len(coins)
	if n < 2 {
		return -1
	}
	limit := coins[n-2] + coins[n-1]
	opt := make([]int, limit)    // оптимум, динамика как в CoinChange
	greedy := make([]int, limit) // жадный ответ
	big := 0                     // индекс самой крупной монеты <= s
	for s := 1; s < limit; s++ {
		opt[s] = s // одними единицами
		for _, c := range coins {
			if c > s {
				break
			}
			opt[s] = min(opt[s], opt[s-c]+1)
		}
		for big+1 < n && coins[big+1] <= s {
			big++
		}
		// жадный берёт самую крупную монету, дальше снова жадничает
		greedy[s] = 1 + greedy[s-coins[big]]
		if greedy[s] > opt[s] {
			return s
		}
	}
	return -1
}
