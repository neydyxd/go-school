package l12dpgreedy

// ChangeWays возвращает число способов набрать сумму amount монетами
// coins (номиналы положительные и различные, монет сколько угодно).
// Способы различаются только набором монет, не порядком: 1+2 и 2+1 это
// один способ. Для amount == 0 есть ровно один способ: не брать ничего.
// Гарантируется, что ответ помещается в int.
//
// Ожидаемая сложность: O(amount * len(coins)). Следи за порядком циклов:
// если внешний цикл идёт по суммам, а внутренний по монетам, посчитаются
// перестановки, а не наборы.
func ChangeWays(amount int, coins []int) int {
	dp := make([]int, amount+1)
	dp[0] = 1
	// внешний цикл по монетам: каждый набор строится в порядке номиналов
	// из coins, поэтому 1+2 и 2+1 считаются один раз
	for _, c := range coins {
		for s := c; s <= amount; s++ {
			dp[s] += dp[s-c]
		}
	}
	return dp[amount]
}
