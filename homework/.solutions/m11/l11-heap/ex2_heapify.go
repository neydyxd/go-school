package l11heap

// Heapify переставляет элементы a на месте так, чтобы слайс стал
// кучей минимумов: a[(i-1)/2] <= a[i] для каждого i > 0.
// Сделай это за O(n): просеивай вниз (sift down) все узлы, у которых
// есть дети, начиная с последнего такого узла и двигаясь к корню.
// Пустой слайс и слайс из одного элемента уже кучи. Не используй
// container/heap, sort и slices: тест проверяет и импорты, и точную
// раскладку, которую даёт именно этот алгоритм.
func Heapify(a []int) {
	// листья (вторая половина слайса) уже кучи из одного элемента
	for i := len(a)/2 - 1; i >= 0; i-- {
		down(a, i)
	}
}

// down это sift down для кучи минимумов (отдельная копия, чтобы файл
// не зависел от решения задачи ex1).
func down(a []int, i int) {
	n := len(a)
	for {
		small := i
		if l := 2*i + 1; l < n && a[l] < a[small] {
			small = l
		}
		if r := 2*i + 2; r < n && a[r] < a[small] {
			small = r
		}
		if small == i {
			return
		}
		a[i], a[small] = a[small], a[i]
		i = small
	}
}
