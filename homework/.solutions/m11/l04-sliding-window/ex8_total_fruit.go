package l04slidingwindow

// TotalFruit получает ряд деревьев, fruits[i]: сорт фруктов на i-м дереве.
// Есть две корзины, в каждую помещается только один сорт (но сколько угодно
// фруктов). Начни с любого дерева и иди вправо, срывая по одному фрукту
// с каждого дерева, пока можешь положить его в корзину. Верни максимальное
// число фруктов, то есть длину самого длинного подотрезка, в котором
// не больше двух разных значений. Пустой слайс: 0.
//
// Ожидаемая сложность: O(n) по времени.
func TotalFruit(fruits []int) int {
	cnt := make(map[int]int)
	best, l := 0, 0
	for r, f := range fruits {
		cnt[f]++
		for len(cnt) > 2 {
			cnt[fruits[l]]--
			if cnt[fruits[l]] == 0 {
				delete(cnt, fruits[l]) // иначе len(cnt) врёт
			}
			l++
		}
		best = max(best, r-l+1)
	}
	return best
}
