package l05stackqueue

// NextGreaterIndex для каждого i возвращает индекс ближайшего справа
// элемента, строго большего nums[i], или -1, если такого нет.
// [2 1 2 4 3] даёт [3 2 3 -1 -1]: для nums[0] = 2 ближайший больший
// это 4 на позиции 3 (равная двойка на позиции 2 не подходит).
// Для пустого входа верни пустой слайс (nil тоже подойдёт).
//
// Ожидаемая сложность: O(n) по времени через монотонный стек индексов.
// Перебор вправо от каждого элемента это O(n^2) на убывающем массиве.
func NextGreaterIndex(nums []int) []int {
	res := make([]int, len(nums))
	var st []int // индексы, значения по ним строго убывают снизу вверх
	for i, v := range nums {
		res[i] = -1
		for len(st) > 0 && nums[st[len(st)-1]] < v {
			res[st[len(st)-1]] = i // v первый больший для вершины
			st = st[:len(st)-1]
		}
		st = append(st, i)
	}
	return res
}
