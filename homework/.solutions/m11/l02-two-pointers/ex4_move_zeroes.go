package l02twopointers

// MoveZeroes на месте переносит все нули в конец nums, сохраняя порядок
// ненулевых элементов: [0 1 0 3 12] -> [1 3 12 0 0].
//
// Ожидаемая сложность: O(n) по времени, O(1) по дополнительной памяти.
func MoveZeroes(nums []int) {
	w := 0 // сюда пишем следующий ненулевой элемент
	for _, v := range nums {
		if v != 0 {
			nums[w] = v
			w++
		}
	}
	clear(nums[w:])
}
