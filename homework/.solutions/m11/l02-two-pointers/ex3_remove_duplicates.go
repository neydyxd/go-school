package l02twopointers

// RemoveDuplicates получает слайс, отсортированный по неубыванию, и на месте
// переносит уникальные значения в его начало в исходном порядке. Верни их
// число k: после вызова nums[:k] содержит каждое значение ровно один раз.
// Что лежит в nums[k:], не важно. Пустой слайс: 0.
//
// Ожидаемая сложность: O(n) по времени, O(1) по дополнительной памяти.
// Удалять элементы через append(nums[:i], nums[i+1:]...) в цикле нельзя:
// каждое такое удаление стоит O(n).
func RemoveDuplicates(nums []int) int {
	if len(nums) == 0 {
		return 0
	}
	k := 1 // nums[:k] уже без повторов
	for i := 1; i < len(nums); i++ {
		if nums[i] != nums[k-1] {
			nums[k] = nums[i]
			k++
		}
	}
	return k
}
