package l02channels

// Generate возвращает канал, из которого можно прочитать все nums по порядку,
// после чего канал закрыт (range по нему завершается).
//
// Generate возвращает канал сразу, не дожидаясь, пока кто-то начнёт читать.
// Отправитель закрывает канал сам: это его ответственность, а не читателя.
// После того как все значения прочитаны, горутина-отправитель (если она есть)
// должна завершиться, а не висеть вечно.
// Без аргументов: канал сразу закрыт.
func Generate(nums ...int) <-chan int {
	out := make(chan int)
	go func() {
		defer close(out)
		for _, n := range nums {
			out <- n
		}
	}()
	return out
}
