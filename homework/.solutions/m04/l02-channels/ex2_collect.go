package l02channels

// Collect читает значения из ch и возвращает их в порядке получения.
// Чтение заканчивается, когда:
//   - канал закрыт и опустел;
//   - или прочитано limit значений (limit <= 0 значит «без лимита»).
//
// Лишнего не читай: если лимит достигнут, остальные значения должны
// остаться в канале.
//
// nil-канал никогда ничего не отдаст, и чтение из него заблокирует
// горутину навсегда. Вместо вечной блокировки сразу верни nil.
func Collect(ch <-chan int, limit int) []int {
	if ch == nil {
		return nil
	}
	var out []int
	for limit <= 0 || len(out) < limit {
		v, ok := <-ch
		if !ok {
			break
		}
		out = append(out, v)
	}
	return out
}
