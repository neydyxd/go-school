package l01goroutines

import "sync"

// ParallelMap применяет f к каждому элементу in и возвращает новый слайс
// результатов в том же порядке, что и вход: out[i] == f(in[i]).
//
// Каждый вызов f выполняется в отдельной горутине, все вызовы идут
// одновременно (тест это проверяет: f ждёт, пока стартуют все остальные).
// Функция возвращается только после того, как отработали все горутины.
// Пустой или nil вход: слайс длины 0. Исходный слайс не меняй.
//
// Подсказка: заранее выдели out нужной длины, тогда каждая горутина
// пишет только в свою ячейку и общий append не нужен.
func ParallelMap(in []int, f func(int) int) []int {
	out := make([]int, len(in))
	var wg sync.WaitGroup
	for i, v := range in {
		// С Go 1.22 i и v свои на каждой итерации, копировать не нужно.
		wg.Go(func() {
			out[i] = f(v)
		})
	}
	wg.Wait()
	return out
}
