package l03select

// Merge сливает два канала в один: всё, что пришло из a и из b, попадает
// в выходной канал. Порядок между a и b любой, но порядок значений
// внутри одного источника сохраняется.
//
// Выходной канал закрывается, когда закрыты оба входа и всё переслано.
// nil-вход считается пустым источником, который уже «закончился»
// (иначе Merge ждала бы его вечно).
//
// Сделай это одной горутиной с select. Подсказка: чтение из закрытого
// канала всегда готово, и select будет крутиться вхолостую. Что можно
// присвоить переменной канала, чтобы её case больше никогда не срабатывал?
func Merge(a, b <-chan int) <-chan int {
	out := make(chan int)
	go func() {
		defer close(out)
		// nil-вход уже «закончился»: цикл ждёт только живые каналы.
		for a != nil || b != nil {
			select {
			case v, ok := <-a:
				if !ok {
					a = nil // case с nil-каналом больше не выберется
					continue
				}
				out <- v
			case v, ok := <-b:
				if !ok {
					b = nil
					continue
				}
				out <- v
			}
		}
	}()
	return out
}
