package l04sync

import "sync"

// Memoize оборачивает дорогую функцию f (например, запрос в базу) кешем.
// Возвращённая функция безопасна для вызова из многих горутин и гарантирует:
//
//   - для каждого ключа f вызывается ровно один раз, даже если 100 горутин
//     одновременно попросили один и тот же ключ: остальные ждут результата
//     первого вызова и получают его же;
//   - ошибка тоже кешируется: повторный вызов с тем же ключом вернёт
//     ту же ошибку, а не вызовет f снова;
//   - разные ключи не ждут друг друга: пока f считает медленный ключ,
//     вызов для другого ключа не должен блокироваться.
//
// Подсказка: мапа «ключ -> запись», где в записи sync.Once и результат.
// Мьютекс держи только на время работы с мапой, но не во время вызова f.
func Memoize(f func(key string) (int, error)) func(key string) (int, error) {
	type entry struct {
		once sync.Once
		val  int
		err  error
	}
	var (
		mu    sync.Mutex
		cache = make(map[string]*entry)
	)
	return func(key string) (int, error) {
		mu.Lock()
		e, ok := cache[key]
		if !ok {
			e = &entry{}
			cache[key] = e
		}
		mu.Unlock()

		// Once сам заставит конкурентов по этому ключу ждать первый вызов,
		// а другие ключи живут в своих записях и не блокируются.
		e.once.Do(func() { e.val, e.err = f(key) })
		return e.val, e.err
	}
}
