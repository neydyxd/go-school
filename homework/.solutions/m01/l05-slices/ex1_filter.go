package l05slices

// Filter возвращает новый слайс из тех элементов s, для которых keep вернул true,
// в исходном порядке.
//
// Исходный слайс менять нельзя: ни значения, ни их порядок. Вызывающий код
// может продолжать пользоваться s после вызова.
// Пустой или nil вход, а также «ничего не подошло»: результат длины 0.
func Filter(s []int, keep func(int) bool) []int {
	// Свой массив под результат. Приём out := s[:0] фильтрует на месте и портит вход.
	out := make([]int, 0, len(s))
	for _, v := range s {
		if keep(v) {
			out = append(out, v)
		}
	}
	return out
}
