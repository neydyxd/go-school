package l03functions

// Memoize возвращает обёртку над f, которая запоминает результаты:
// для каждого аргумента f вызывается не больше одного раза,
// повторные вызовы берут ответ из кеша.
// У каждой обёртки свой кеш: две Memoize(f) не делят результаты.
// Кеш удобно держать в map[int]int внутри замыкания (мапы подробно будут в уроке про мапы).
func Memoize(f func(int) int) func(int) int {
	cache := map[int]int{} // не потокобезопасно: из нескольких горутин нужен мьютекс
	return func(x int) int {
		if v, ok := cache[x]; ok {
			return v
		}
		v := f(x)
		cache[x] = v
		return v
	}
}
