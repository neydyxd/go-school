package l04pointers

// Swap меняет местами значения, на которые указывают a и b.
// Если хотя бы один указатель nil, ничего не делает (и не паникует).
// a и b могут указывать на одну и ту же переменную: тогда значение не меняется.
func Swap(a, b *int) {
	if a == nil || b == nil {
		return
	}
	*a, *b = *b, *a // правая часть вычисляется целиком до присваивания
}
