// Slug превращает заголовок статьи в кусок URL: "Привет, Go 1.24!" -> "привет-go-1-24".
// Это готовая и правильная функция, менять её не нужно.
//
// Правила:
//   - буквы любого алфавита и цифры сохраняются, буквы переводятся в нижний регистр;
//   - любая серия других символов (пробелы, знаки препинания, _) становится одним дефисом;
//   - дефисов в начале и в конце нет;
//   - пустой ввод и ввод без букв и цифр дают "".
func Slug(s string) string {
	var b strings.Builder
	sep := false
	for _, r := range s {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			sep = true
			continue
		}
		if sep && b.Len() > 0 {
			b.WriteByte('-')
		}
		sep = false
		b.WriteRune(unicode.ToLower(r))
	}
	return b.String()
}

